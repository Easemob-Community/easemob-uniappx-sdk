/// 解决问题：类的只读枚举属性，使用 setValue 崩溃
func setReadonlyProperty<T>(obj: NSObject, key: String, value: T) {    
    let ivarName = "_" + key
    guard let ivar = class_getInstanceVariable(type(of: obj), ivarName) else {
        print("Not find ivar: \(ivarName)")
        return
    }
    
    let offset = ivar_getOffset(ivar)
    withUnsafePointer(to: value) { valuePtr in
        let rawPtr = UnsafeMutableRawPointer(bitPattern: Int(bitPattern: Unmanaged.passUnretained(obj).toOpaque()) + Int(offset))
        rawPtr?.copyMemory(from: valuePtr, byteCount: MemoryLayout<T>.size)
    }
}

